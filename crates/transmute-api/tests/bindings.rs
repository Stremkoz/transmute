//! The TypeScript types the frontend compiles against, generated from the
//! Rust types (ts-rs) and committed in `crates/transmute-api/bindings/`.
//!
//! This test fails when they're out of date. Regenerate with:
//!
//! ```sh
//! TRANSMUTE_UPDATE_BINDINGS=1 cargo test -p transmute-api --test bindings
//! ```

// Test-only file: helpers panic on setup failures, which is what a test wants.
#![allow(clippy::unwrap_used)]

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

use transmute_api::types::*;
use transmute_core::preset::{Preset, UserDefaults};
use transmute_core::settings::AppSettings;

/// Everything the commands take or return, and the events. Types they
/// refer to are exported along with them.
fn export_all(dir: &Path) {
    // Sizes and counts stay far below 2^53, and JSON carries them as numbers.
    let cfg = Config::new().with_out_dir(dir).with_large_int("number");
    Overview::export_all(&cfg).unwrap();
    InputsSummary::export_all(&cfg).unwrap();
    TreeNode::export_all(&cfg).unwrap();
    PlanSummary::export_all(&cfg).unwrap();
    JobPage::export_all(&cfg).unwrap();
    JobFilter::export_all(&cfg).unwrap();
    FileFilter::export_all(&cfg).unwrap();
    FilePage::export_all(&cfg).unwrap();
    EntryDetails::export_all(&cfg).unwrap();
    TargetTotals::export_all(&cfg).unwrap();
    ApiEvent::export_all(&cfg).unwrap();
    ToolInfo::export_all(&cfg).unwrap();
    StoredPreset::export_all(&cfg).unwrap();
    PreviewTarget::export_all(&cfg).unwrap();
    Preview::export_all(&cfg).unwrap();
    Sample::export_all(&cfg).unwrap();
    ApiError::export_all(&cfg).unwrap();
    Preset::export_all(&cfg).unwrap();
    UserDefaults::export_all(&cfg).unwrap();
    AppSettings::export_all(&cfg).unwrap();
    CodecDefaults::export_all(&cfg).unwrap();

    // One import point for the frontend.
    let mut names: Vec<String> = fs::read_dir(dir)
        .unwrap()
        .filter_map(|e| e.unwrap().file_name().into_string().ok())
        .filter_map(|n| n.strip_suffix(".ts").map(str::to_owned))
        .filter(|n| n != "index")
        .collect();
    names.sort();
    let index: String = std::iter::once(
        "// Generated by crates/transmute-api/tests/bindings.rs. Don't edit.\n".to_owned(),
    )
    .chain(
        names
            .iter()
            .map(|n| format!("export type * from \"./{n}\";\n")),
    )
    .collect();
    fs::write(dir.join("index.ts"), index).unwrap();
}

/// File name → contents, with line endings normalised.
fn read_all(dir: &Path) -> BTreeMap<String, String> {
    let Ok(entries) = fs::read_dir(dir) else {
        return BTreeMap::new();
    };
    entries
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "ts"))
        .map(|p| {
            let name = p.file_name().unwrap().to_string_lossy().into_owned();
            (name, fs::read_to_string(&p).unwrap().replace("\r\n", "\n"))
        })
        .collect()
}

#[test]
fn typescript_bindings_are_current() {
    let committed: PathBuf = Path::new(env!("CARGO_MANIFEST_DIR")).join("bindings");
    let fresh = tempfile::tempdir().unwrap();
    export_all(fresh.path());

    if std::env::var("TRANSMUTE_UPDATE_BINDINGS").is_ok_and(|v| v == "1") {
        let _ = fs::remove_dir_all(&committed);
        fs::create_dir_all(&committed).unwrap();
        for (name, contents) in read_all(fresh.path()) {
            fs::write(committed.join(name), contents).unwrap();
        }
        return;
    }

    let expected = read_all(fresh.path());
    let actual = read_all(&committed);
    let stale: Vec<&String> = expected
        .keys()
        .chain(actual.keys())
        .filter(|name| expected.get(*name) != actual.get(*name))
        .collect();
    assert!(
        stale.is_empty(),
        "TypeScript bindings are out of date ({stale:?}). Regenerate with:\n  \
         TRANSMUTE_UPDATE_BINDINGS=1 cargo test -p transmute-api --test bindings"
    );
}
